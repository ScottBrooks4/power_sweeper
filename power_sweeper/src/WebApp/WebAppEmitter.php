    /** @param array<string, mixed> $ir */
    public function renderJs(array $ir, string $serverLanguage = 'php'): string
    {
        $api = $serverLanguage === 'python' ? 'api.py' : 'api.php';

        return <<<JS
(() => {
  const ir = window.PS_IR || { screens: [], navigation: [] };
  const nav = document.getElementById("nav");
  const state = { vars: Object.create(null), screen: (ir.screens[0] && ir.screens[0].name) || "" };
  const API = "{$api}";

  function show(name) {
    state.screen = name;
    document.querySelectorAll(".nav-btn").forEach((b) => b.classList.toggle("active", b.dataset.screen === name));
    document.querySelectorAll(".ps-screen").forEach((s) => s.classList.toggle("active", s.dataset.screen === name));
    const focus = (ir.navigation || []).find((e) => e.to === name && e.kind === "setfocus");
    if (focus && focus.to) {
      const el = document.querySelector('[data-name="' + cssEscape(focus.to) + '"] input, [data-name="' + cssEscape(focus.to) + '"]');
      if (el && el.focus) el.focus();
    }
  }

  function cssEscape(s) {
    return String(s).replace(/[\\\\"]/g, (ch) => "\\\\" + ch);
  }

  function ctrl(name) {
    return document.querySelector('[data-name="' + cssEscape(name) + '"]');
  }

  function readValue(el) {
    if (!el) return "";
    const input = el.matches("input,select,textarea") ? el : el.querySelector("input,select,textarea");
    if (input) {
      if (input.type === "checkbox") return input.checked;
      return input.value;
    }
    return (el.dataset.value != null ? el.dataset.value : el.textContent || "").trim();
  }

  function fx(expr, host) {
    if (expr == null) return "";
    let s = String(expr).trim();
    if (s.startsWith("=")) s = s.slice(1).trim();
    if (s === "") return "";
    if (/^true$/i.test(s)) return true;
    if (/^false$/i.test(s)) return false;
    if (/^"[^"]*"$/.test(s) || /^'[^']*'$/.test(s)) return s.slice(1, -1);
    if (/^-?\\d+(\\.\\d+)?$/.test(s)) return Number(s);
    const rgba = s.match(/^RGBA?\\(\\s*(\\d+)\\s*,\\s*(\\d+)\\s*,\\s*(\\d+)\\s*(?:,\\s*([0-9.]+)\\s*)?\\)$/i);
    if (rgba) {
      const a = rgba[4] == null ? 1 : Number(rgba[4]);
      return a < 1 ? "rgba(" + rgba[1] + ", " + rgba[2] + ", " + rgba[3] + ", " + a + ")" : "rgb(" + rgba[1] + ", " + rgba[2] + ", " + rgba[3] + ")";
    }
    const navm = s.match(/^Navigate\\(\\s*(?:'([^']+)'|"([^"]+)"|([A-Za-z_][\\w]*))/i);
    if (navm) {
      show(navm[1] || navm[2] || navm[3]);
      return true;
    }
    const setm = s.match(/^Set\\(\\s*([A-Za-z_][\\w]*)\\s*,\\s*(.+)\\)\\s*$/i);
    if (setm) {
      state.vars[setm[1]] = fx(setm[2], host);
      return state.vars[setm[1]];
    }
    const ifm = s.match(/^If\\(\\s*(.+?)\\s*,\\s*(.+?)\\s*,\\s*(.+)\\)\\s*$/i);
    if (ifm) {
      return fx(ifm[1], host) ? fx(ifm[2], host) : fx(ifm[3], host);
    }
    const ref = s.match(/^([A-Za-z_][\\w]*)\\.(Text|Value|SelectedDate|Selected|HintText|Color)$/);
    if (ref) {
      const node = ctrl(ref[1]);
      if (ref[2] === "Selected" && node) {
        const sel = node.querySelector("select");
        return sel ? { Value: sel.value } : readValue(node);
      }
      return readValue(node);
    }
    if (Object.prototype.hasOwnProperty.call(state.vars, s)) return state.vars[s];
    return s;
  }

  function runFormula(expr, host) {
    if (!expr) return;
    String(expr).split(/;(?!;)/).forEach((part) => {
      const t = part.trim();
      if (t) fx(t, host);
    });
  }

  function bind(el) {
    const events = (() => {
      try { return JSON.parse(el.dataset.events || "{}"); } catch { return {}; }
    })();
    Object.entries(events).forEach(([evt, formula]) => {
      el.addEventListener(evt, () => runFormula(formula, el));
    });
  }

  function playerConfig() {
    const layout = (ir.document && ir.document.layout) || {};
    const player = (ir.document && ir.document.player) || {};
    const w = Number(player.width || layout.width || 1366) || 1366;
    const h = Number(player.height || layout.height || 768) || 768;
    return {
      width: w,
      height: h,
      scaleToFit: player.scale_to_fit !== false,
      maintainAspectRatio: player.maintain_aspect_ratio !== false,
    };
  }

  function fitCanvas() {
    const cfg = playerConfig();
    const vp = document.getElementById("viewport");
    if (!vp) return null;
    const availW = Math.max(1, vp.clientWidth);
    const availH = Math.max(1, vp.clientHeight);
    const scale = fitScale(cfg.width, cfg.height, availW, availH, cfg.scaleToFit, cfg.maintainAspectRatio);
    const fitW = cfg.width * scale.x;
    const fitH = cfg.height * scale.y;
    const root = document.documentElement;
    root.style.setProperty("--ps-design-w", cfg.width + "px");
    root.style.setProperty("--ps-design-h", cfg.height + "px");
    root.style.setProperty("--ps-scale-x", String(scale.x));
    root.style.setProperty("--ps-scale-y", String(scale.y));
    root.style.setProperty("--ps-fit-w", fitW + "px");
    root.style.setProperty("--ps-fit-h", fitH + "px");
    const stage = document.getElementById("stage");
    if (stage) {
      stage.dataset.scaleX = String(scale.x);
      stage.dataset.scaleY = String(scale.y);
    }
    return { x: scale.x, y: scale.y, width: fitW, height: fitH, design: cfg };
  }

  function fitScale(designW, designH, availW, availH, scaleToFit, keepRatio) {
    if (!scaleToFit || designW <= 0 || designH <= 0) {
      return { x: 1, y: 1 };
    }
    if (keepRatio !== false) {
      const s = Math.min(availW / designW, availH / designH);
      return { x: s, y: s };
    }
    return { x: availW / designW, y: availH / designH };
  }

  document.querySelectorAll(".ps-ctrl").forEach(bind);
  nav?.addEventListener("click", (e) => {
    const btn = e.target.closest(".nav-btn");
    if (btn) show(btn.dataset.screen);
  });
  window.addEventListener("resize", fitCanvas);
  window.visualViewport?.addEventListener("resize", fitCanvas);
  window.addEventListener("orientationchange", () => setTimeout(fitCanvas, 50));
  if (state.screen) show(state.screen);
  const scale = fitCanvas();

  window.PS = { show, fx, runFormula, state, api: API, fitCanvas, fitScale, scale };
})();

JS;
    }

    /**
     * Power Apps player math: keep design X/Y, scale the whole canvas to the device.
     *
     * @return array{x:float,y:float}
     */
    public static function fitScale(
        int $designW,
        int $designH,
        int $availW,
        int $availH,
        bool $scaleToFit = true,
        bool $maintainAspectRatio = true,
    ): array {
        if (!$scaleToFit || $designW <= 0 || $designH <= 0) {
            return ['x' => 1.0, 'y' => 1.0];
        }
        if ($maintainAspectRatio) {
            $s = min($availW / $designW, $availH / $designH);

            return ['x' => $s, 'y' => $s];
        }

        return ['x' => $availW / $designW, 'y' => $availH / $designH];
    }

    /**
     * @param array<string, mixed> $ir
     * @return array{width:int,height:int,scale_to_fit:bool,maintain_aspect_ratio:bool}
     */
    public static function playerConfig(array $ir): array
    {
        $document = is_array($ir['document'] ?? null) ? $ir['document'] : [];
        $document = WebAppIrBuilder::withPlayer($document);
        $player = is_array($document['player'] ?? null) ? $document['player'] : [];

        return [
            'width' => (int) ($player['width'] ?? 1366),
            'height' => (int) ($player['height'] ?? 768),
            'scale_to_fit' => (bool) ($player['scale_to_fit'] ?? true),
            'maintain_aspect_ratio' => (bool) ($player['maintain_aspect_ratio'] ?? true),
        ];
    }

    /**
     * @param array<string, mixed> $node
     */
    private function renderControl(array $node, int $depth): string
    {
        $name = (string) ($node['name'] ?? '');
        $web = is_array($node['web'] ?? null) ? $node['web'] : [];
        $tag = (string) ($web['html'] ?? 'div');
        if (!preg_match('/^[a-z][a-z0-9]*$/', $tag)) {
            $tag = 'div';
        }
        $role = htmlspecialchars((string) ($node['role'] ?? $web['role'] ?? 'control'), ENT_QUOTES);
        $key = htmlspecialchars((string) ($web['key'] ?? ''), ENT_QUOTES);
        $safeName = htmlspecialchars($name, ENT_QUOTES);
        $variant = strtolower((string) ($node['variant'] ?? ''));
        $auto = str_contains($variant, 'auto');
        $style = $this->inlineStyle($node);
        $labels = is_array($node['labels'] ?? null) ? $node['labels'] : [];
        $props = is_array($node['properties'] ?? null) ? $node['properties'] : [];
        $formulas = is_array($node['formulas'] ?? null) ? $node['formulas'] : [];
        $events = is_array($web['events'] ?? null) ? $web['events'] : [];
        $eventMap = [];
        foreach ($events as $domEvt => $paProp) {
            $formula = (string) ($formulas[(string) $paProp] ?? $props[(string) $paProp] ?? '');
            if ($formula !== '') {
                $eventMap[(string) $domEvt] = $formula;
            }
        }
        $eventAttr = htmlspecialchars(json_encode($eventMap, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES) ?: '{}', ENT_QUOTES);
        $hidden = $this->isFalseyLiteral($props['Visible'] ?? null) ? 'true' : 'false';
        $disabled = $this->isDisabled($props['DisplayMode'] ?? null) ? 'true' : 'false';
        $cls = 'ps-ctrl' . ($auto ? ' auto' : '') . ($role === 'choice' ? ' choice' : '');
        $open = '<' . $tag
            . ' class="' . $cls . '"'
            . ' data-name="' . $safeName . '"'
            . ' data-role="' . $role . '"'
            . ' data-web-key="' . $key . '"'
            . ' data-hidden="' . $hidden . '"'
            . ' data-disabled="' . $disabled . '"'
            . ' data-events="' . $eventAttr . '"'
            . ' style="' . htmlspecialchars($style, ENT_QUOTES) . '">';

        $inner = $this->innerHtml($tag, $web, $labels, $props);
        $kids = '';
        foreach (is_array($node['children'] ?? null) ? $node['children'] : [] as $child) {
            if (is_array($child)) {
                $kids .= $this->renderControl($child, $depth + 1);
            }
        }

        if (in_array($tag, ['img', 'input'], true)) {
            return $this->voidControl($tag, $web, $labels, $props, $cls, $safeName, $role, $key, $hidden, $disabled, $eventAttr, $style);
        }

        return $open . $inner . $kids . '</' . $tag . '>';
    }

    /**
     * @param array<string, mixed> $web
     * @param array<string, mixed> $labels
     * @param array<string, mixed> $props
     */
    private function voidControl(
        string $tag,
        array $web,
        array $labels,
        array $props,
        string $cls,
        string $safeName,
        string $role,
        string $key,
        string $hidden,
        string $disabled,
        string $eventAttr,
        string $style,
    ): string {
        $extra = '';
        if ($tag === 'input') {
            $type = htmlspecialchars((string) ($web['input_type'] ?? 'text'), ENT_QUOTES);
            $value = htmlspecialchars($this->literalText((string) ($props['Default'] ?? $props['DefaultDate'] ?? $props['Value'] ?? $labels['Text'] ?? '')), ENT_QUOTES);
            $ph = htmlspecialchars($this->literalText((string) ($props['HintText'] ?? $props['Placeholder'] ?? $labels['HintText'] ?? '')), ENT_QUOTES);
            $extra = ' type="' . $type . '" value="' . $this->dateInputValue($type, $value) . '"';
            if ($ph !== '') {
                $extra .= ' placeholder="' . $ph . '"';
            }
            if ($disabled === 'true') {
                $extra .= ' disabled';
            }
        }
        if ($tag === 'img') {
            $src = htmlspecialchars($this->literalText((string) ($props['Image'] ?? '')), ENT_QUOTES);
            $alt = htmlspecialchars($this->literalText((string) ($labels['AccessibleLabel'] ?? $labels['Text'] ?? $safeName)), ENT_QUOTES);
            $extra = ' src="' . $src . '" alt="' . $alt . '"';
        }

        return '<' . $tag
            . ' class="' . $cls . '"'
            . ' data-name="' . $safeName . '"'
            . ' data-role="' . $role . '"'
            . ' data-web-key="' . $key . '"'
            . ' data-hidden="' . $hidden . '"'
            . ' data-disabled="' . $disabled . '"'
            . ' data-events="' . $eventAttr . '"'
            . ' style="' . htmlspecialchars($style, ENT_QUOTES) . '"'
            . $extra
            . '>';
    }

    /**
     * @param array<string, mixed> $web
     * @param array<string, mixed> $labels
     * @param array<string, mixed> $props
     */
    private function innerHtml(string $tag, array $web, array $labels, array $props): string
    {
        if ($tag === 'select') {
            $items = $this->literalItems((string) ($props['Items'] ?? ''));
            $html = '';
            foreach ($items as $item) {
                $html .= '<option value="' . htmlspecialchars($item, ENT_QUOTES) . '">' . htmlspecialchars($item, ENT_QUOTES) . '</option>';
            }

            return $html;
        }
        if ($tag === 'button') {
            $text = $this->literalText((string) ($labels['Text'] ?? $props['Text'] ?? ''));

            return htmlspecialchars($text, ENT_QUOTES);
        }
        if (($web['key'] ?? '') === 'checkbox' || ($web['key'] ?? '') === 'toggle') {
            $text = $this->literalText((string) ($labels['Text'] ?? $props['Text'] ?? $props['TrueText'] ?? $labels['Label'] ?? ''));
            $checked = preg_match('/true/i', (string) ($props['Default'] ?? $props['Checked'] ?? '')) === 1 ? ' checked' : '';

            return '<input type="checkbox"' . $checked . '><span>' . htmlspecialchars($text, ENT_QUOTES) . '</span>';
        }
        if ($tag === 'fieldset') {
            $items = $this->literalItems((string) ($props['Items'] ?? ''));
            $html = '';
            $name = 'r' . substr(md5((string) ($props['Items'] ?? uniqid())), 0, 6);
            foreach ($items as $item) {
                $html .= '<label><input type="radio" name="' . $name . '" value="' . htmlspecialchars($item, ENT_QUOTES) . '"> ' . htmlspecialchars($item, ENT_QUOTES) . '</label>';
            }

            return $html;
        }
        if (($web['key'] ?? '') === 'html') {
            return (string) ($labels['HtmlText'] ?? $props['HtmlText'] ?? '');
        }
        $text = $this->literalText((string) ($labels['Text'] ?? $props['Text'] ?? ''));

        return $text === '' ? '' : htmlspecialchars($text, ENT_QUOTES);
    }

    /** @param array<string, mixed> $node */
    private function inlineStyle(array $node): string
    {
        $layout = is_array($node['layout'] ?? null) ? $node['layout'] : [];
        $chrome = is_array($node['chrome'] ?? null) ? $node['chrome'] : [];
        $parts = [];
        foreach (['x' => 'left', 'y' => 'top', 'width' => 'width', 'height' => 'height'] as $key => $css) {
            if (isset($layout[$key]) && is_numeric($layout[$key])) {
                $parts[] = $css . ':' . (int) round((float) $layout[$key]) . 'px';
            }
        }
        $fill = $this->cssColor((string) ($chrome['fill'] ?? ''));
        $color = $this->cssColor((string) ($chrome['color'] ?? ''));
        $border = $this->cssColor((string) ($chrome['border_color'] ?? ''));
        if ($fill !== '') {
            $parts[] = 'background:' . $fill;
        }
        if ($color !== '') {
            $parts[] = 'color:' . $color;
        }
        if (isset($chrome['font_size']) && is_numeric($chrome['font_size']) && (float) $chrome['font_size'] > 0) {
            $parts[] = 'font-size:' . rtrim(rtrim(sprintf('%.2F', (float) $chrome['font_size']), '0'), '.') . 'px';
        }
        if (!empty($chrome['font_weight'])) {
            $parts[] = 'font-weight:' . $this->cssFontWeight((string) $chrome['font_weight']);
        }
        if (!empty($chrome['font_family'])) {
            $parts[] = 'font-family:' . $this->cssFont((string) $chrome['font_family']);
        }
        if (!empty($chrome['align'])) {
            $parts[] = 'text-align:' . $this->cssAlign((string) $chrome['align']);
        }
        $thickness = isset($chrome['border_thickness']) && is_numeric($chrome['border_thickness'])
            ? (float) $chrome['border_thickness']
            : null;
        if ($thickness !== null && $thickness > 0) {
            $parts[] = 'border-style:solid';
            $parts[] = 'border-width:' . $thickness . 'px';
            if ($border !== '') {
                $parts[] = 'border-color:' . $border;
            }
        }
        $radius = $chrome['radius'] ?? null;
        if (is_numeric($radius) && (float) $radius > 0) {
            $parts[] = 'border-radius:' . (float) $radius . 'px';
        } elseif (is_array($radius)) {
            $tl = (float) ($radius['top_left'] ?? 0);
            $tr = (float) ($radius['top_right'] ?? 0);
            $br = (float) ($radius['bottom_right'] ?? 0);
            $bl = (float) ($radius['bottom_left'] ?? 0);
            if ($tl + $tr + $br + $bl > 0) {
                $parts[] = 'border-radius:' . $tl . 'px ' . $tr . 'px ' . $br . 'px ' . $bl . 'px';
            }
        }
        foreach (['padding_top' => 'padding-top', 'padding_right' => 'padding-right', 'padding_bottom' => 'padding-bottom', 'padding_left' => 'padding-left'] as $key => $css) {
            if (isset($chrome[$key]) && is_numeric($chrome[$key])) {
                $parts[] = $css . ':' . (float) $chrome[$key] . 'px';
            }
        }

        return implode(';', $parts);
    }

    private function cssColor(string $formula): string
    {
        $trim = trim($formula);
        if ($trim === '') {
            return '';
        }
        if (preg_match('/gblTheme(?:Light|Dark)?\.([A-Za-z_]\w*)/', $trim, $m) === 1) {
            return 'var(--ps-' . $m[1] . ')';
        }
        $parsed = ColorValue::parse($trim);

        return $parsed !== null ? ColorValue::toCss($parsed) : '';
    }

    private function cssFontWeight(string $raw): string
    {
        $body = trim(ltrim($raw, '='));
        if (preg_match('/Bold|Semibold|Demi/i', $body) === 1) {
            return '600';
        }
        if (preg_match('/Light|Lighter/i', $body) === 1) {
            return '300';
        }

        return is_numeric($body) ? $body : '400';
    }

    private function cssFont(string $raw): string
    {
        $body = trim(ltrim($raw, '='));
        $body = preg_replace("/^Font\\./", '', $body) ?? $body;

        return '"' . addcslashes($body, '"') . '", "Segoe UI", sans-serif';
    }

    private function cssAlign(string $raw): string
    {
        $body = strtolower(trim(ltrim($raw, '=')));
        if (str_contains($body, 'center')) {
            return 'center';
        }
        if (str_contains($body, 'right') || str_contains($body, 'end')) {
            return 'right';
        }

        return 'left';
    }

    private function literalText(string $value): string
    {
        $v = trim($value);
        if (str_starts_with($v, '=')) {
            $v = substr($v, 1);
        }
        $v = trim($v);
        if (
            (str_starts_with($v, '"') && str_ends_with($v, '"'))
            || (str_starts_with($v, "'") && str_ends_with($v, "'"))
        ) {
            $v = substr($v, 1, -1);
        }
        if (preg_match('/\b(If|Switch|LookUp|Filter|Navigate|Set|ThisItem)\s*\(/i', $v) === 1) {
            return '';
        }

        return $v;
    }

    /** @return list<string> */
    private function literalItems(string $formula): array
    {
        $body = trim(ltrim(trim($formula), '='));
        if (preg_match_all('/"([^"]*)"|\'([^\']*)\'/', $body, $m) < 1) {
            return [];
        }
        $out = [];
        foreach ($m[0] as $i => $_) {
            $item = $m[1][$i] !== '' ? $m[1][$i] : $m[2][$i];
            if ($item !== '') {
                $out[] = $item;
            }
        }

        return $out;
    }

    private function dateInputValue(string $type, string $value): string
    {
        if ($type !== 'date') {
            return $value;
        }
        if (preg_match('/Date\\(\\s*(\\d{4})\\s*,\\s*(\\d{1,2})\\s*,\\s*(\\d{1,2})\\s*\\)/i', $value, $m) === 1) {
            return sprintf('%04d-%02d-%02d', (int) $m[1], (int) $m[2], (int) $m[3]);
        }
        if (preg_match('/^\\d{4}-\\d{2}-\\d{2}$/', $value) === 1) {
            return $value;
        }

        return '';
    }

    private function isFalseyLiteral(mixed $value): bool
    {
        if (!is_string($value)) {
            return false;
        }
        $body = strtolower(trim(ltrim(trim($value), '=')));

        return $body === 'false';
    }

    private function isDisabled(mixed $value): bool
    {
        if (!is_string($value)) {
            return false;
        }

        return preg_match('/DisplayMode\.(Disabled|View)/i', $value) === 1;
    }

