<?php

declare(strict_types=1);

namespace PowerSweeper\WebApp;

use PowerSweeper\ColorValue;

/**
 * Emit a pixel-positioned web app from IR (HTML/CSS/JS + server stub).
 */
final class WebAppEmitter
{
    /**
     * @param array<string, mixed> $ir
     * @return array<string, string> relative WebApp/ path => file contents
     */
    public function emitFiles(array $ir, string $serverLanguage = 'php'): array
    {
        $serverLanguage = $serverLanguage === 'python' ? 'python' : 'php';
        $files = [
            'index.html' => $this->renderHtml($ir, $serverLanguage),
            'app.css' => $this->renderCss($ir),
            'app.js' => $this->renderJs($ir, $serverLanguage),
        ];
        $server = (new WebAppServerEmitter())->emit($ir, $serverLanguage);
        $files[$serverLanguage === 'python' ? 'api.py' : 'api.php'] = $server;
        $files['README.md'] = $this->readme($ir, $serverLanguage);

        return $files;
    }

    /** @param array<string, mixed> $ir */
    public function renderHtml(array $ir, string $serverLanguage = 'php'): string
    {
        $title = htmlspecialchars((string) (($ir['document']['name'] ?? null) ?: 'Power Sweeper Web App'), ENT_QUOTES);
        $screens = is_array($ir['screens'] ?? null) ? $ir['screens'] : [];
        $nav = is_array($ir['navigation'] ?? null) ? $ir['navigation'] : [];
        $player = self::playerConfig($ir);
        $canvasW = $player['width'];
        $canvasH = $player['height'];

        $navBtns = '';
        $bodies = '';
        foreach ($screens as $index => $screen) {
            if (!is_array($screen)) {
                continue;
            }
            $name = (string) ($screen['name'] ?? '');
            if ($name === '') {
                continue;
            }
            $safe = htmlspecialchars($name, ENT_QUOTES);
            $active = $index === 0 ? ' active' : '';
            $navBtns .= '<button type="button" class="nav-btn' . $active . '" data-screen="' . $safe . '">' . $safe . '</button>';
            $fill = $this->cssColor((string) (($screen['chrome']['fill'] ?? '') ?: ''));
            $style = 'width:100%;height:100%;';
            if ($fill !== '') {
                $style .= 'background:' . $fill . ';';
            }
            $bodies .= '<section class="ps-screen' . $active . '" data-screen="' . $safe . '" style="' . $style . '">';
            foreach (is_array($screen['children'] ?? null) ? $screen['children'] : [] as $child) {
                if (is_array($child)) {
                    $bodies .= $this->renderControl($child, 0);
                }
            }
            $bodies .= '</section>';
        }

        $screensJson = json_encode($screens, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: '[]';
        $navJson = json_encode($nav, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: '[]';
        $themeJson = json_encode(
            is_array($ir['theme_tokens'] ?? null) ? $ir['theme_tokens'] : [],
            JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
        ) ?: '[]';
        $server = htmlspecialchars($serverLanguage, ENT_QUOTES);
        $scaleAttr = $player['scale_to_fit'] ? 'true' : 'false';
        $docJson = json_encode(
            is_array($ir['document'] ?? null) ? $ir['document'] : [],
            JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
        ) ?: '{}';

        return <<<HTML
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>{$title}</title>
  <link rel="stylesheet" href="app.css">
</head>
<body data-server="{$server}" data-scale-to-fit="{$scaleAttr}">
  <header class="ps-chrome">
    <h1>{$title}</h1>
    <p>Pixel-positioned conversion from Power Apps YAML/JSON. Structural preview of screens, labels, and navigation — same layout and control behaviors. The design canvas ({$canvasW}×{$canvasH}) scale-to-fits each device.</p>
  </header>
  <nav class="nav" id="nav">{$navBtns}</nav>
  <div class="ps-viewport" id="viewport">
    <main class="ps-stage" id="stage">
      <div class="ps-canvas" id="canvas" style="width:{$canvasW}px;height:{$canvasH}px">{$bodies}</div>
    </main>
  </div>
  <footer class="ps-chrome">Generated by Power Sweeper export_web_ir · server={$server}. Edit IR then run import_from_web_ir to write labels/layout back.</footer>
  <script>window.PS_IR = {screens: {$screensJson}, navigation: {$navJson}, theme_tokens: {$themeJson}, document: {$docJson}, server: "{$server}"};</script>
  <script src="app.js"></script>
</body>
</html>
HTML;
    }

