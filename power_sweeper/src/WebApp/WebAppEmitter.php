            'Danger' => '#dc2626',
            'Success' => '#16a34a',
        ];
        foreach ($defaults as $name => $color) {
            if ($tokens === [] || in_array($name, $tokens, true)) {
                $vars .= "  --ps-{$name}: {$color};\n";
            }
        }
        $player = self::playerConfig($ir);
        $designW = $player['width'];
        $designH = $player['height'];

