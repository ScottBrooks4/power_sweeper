<?php

declare(strict_types=1);

namespace PowerSweeper\WebApp;

/**
 * Emit the server half of a converted canvas app (PHP or Python, same JSON contract).
 */
final class WebAppServerEmitter
{
    /**
     * @param array<string, mixed> $ir
     */
    public function emit(array $ir, string $language): string
    {
        $language = $language === 'python' ? 'python' : 'php';
        $datasources = [];
        foreach (is_array($ir['datasources'] ?? null) ? $ir['datasources'] : [] as $name) {
            if (is_string($name) && $name !== '') {
                $datasources[] = $name;
            }
        }
        $title = (string) (($ir['document']['name'] ?? null) ?: 'Power Sweeper Web App');

        return $language === 'python'
            ? $this->python($title, $datasources)
            : $this->php($title, $datasources);
    }

    /**
     * @param list<string> $datasources
     */
    private function php(string $title, array $datasources): string
    {
        $dsJson = json_encode($datasources, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: '[]';
        $safeTitle = addcslashes($title, "\\'");

        return <<<PHP
<?php
/**
 * Generated by Power Sweeper export_web_ir (server_language=php).
 * Same JSON contract as api.py — test PHP first; switch the sweep option to python later.
 *
 *   php -S localhost:8787 api.php
 */
declare(strict_types=1);

header('Access-Control-Allow-Origin: *');
header('Access-Control-Allow-Methods: GET, POST, OPTIONS');
header('Access-Control-Allow-Headers: Content-Type');
if ((\$_SERVER['REQUEST_METHOD'] ?? '') === 'OPTIONS') {
    http_response_code(204);
    exit;
}

\$route = (string) (\$_GET['route'] ?? \$_POST['route'] ?? 'health');
\$store = __DIR__ . DIRECTORY_SEPARATOR . 'data';
if (!is_dir(\$store)) {
    @mkdir(\$store, 0775, true);
}
\$datasources = json_decode('{$dsJson}', true);
if (!is_array(\$datasources)) {
    \$datasources = [];
}

function ps_json(mixed \$payload, int \$code = 200): void
{
    http_response_code(\$code);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode(\$payload, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
    exit;
}

function ps_read(string \$store, string \$name): array
{
    \$path = \$store . DIRECTORY_SEPARATOR . preg_replace('/[^A-Za-z0-9._-]+/', '_', \$name) . '.json';
    if (!is_file(\$path)) {
        return [];
    }
    \$raw = file_get_contents(\$path);
    \$data = is_string(\$raw) ? json_decode(\$raw, true) : null;

    return is_array(\$data) ? \$data : [];
}

function ps_write(string \$store, string \$name, array \$rows): void
{
    \$path = \$store . DIRECTORY_SEPARATOR . preg_replace('/[^A-Za-z0-9._-]+/', '_', \$name) . '.json';
    file_put_contents(\$path, json_encode(array_values(\$rows), JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES));
}

\$body = [];
if ((\$_SERVER['REQUEST_METHOD'] ?? '') === 'POST') {
    \$raw = file_get_contents('php://input');
    if (is_string(\$raw) && \$raw !== '') {
        \$decoded = json_decode(\$raw, true);
        if (is_array(\$decoded)) {
            \$body = \$decoded;
        }
    }
}

switch (\$route) {
    case 'health':
        ps_json([
            'ok' => true,
            'app' => '{$safeTitle}',
            'language' => 'php',
            'datasources' => \$datasources,
        ]);
        break;
    case 'lists':
        ps_json(['ok' => true, 'datasources' => \$datasources]);
        break;
    case 'items':
        \$list = (string) (\$body['list'] ?? \$_GET['list'] ?? '');
        if (\$list === '' || !in_array(\$list, \$datasources, true)) {
            ps_json(['ok' => false, 'error' => 'unknown list'], 404);
        }
        ps_json(['ok' => true, 'list' => \$list, 'items' => ps_read(\$store, \$list)]);
        break;
    case 'patch':
        \$list = (string) (\$body['list'] ?? '');
        \$item = is_array(\$body['item'] ?? null) ? \$body['item'] : [];
        if (\$list === '' || !in_array(\$list, \$datasources, true)) {
            ps_json(['ok' => false, 'error' => 'unknown list'], 404);
        }
        \$rows = ps_read(\$store, \$list);
        \$id = (string) (\$item['id'] ?? \$item['ID'] ?? uniqid('row_', true));
        \$item['id'] = \$id;
        \$replaced = false;
        foreach (\$rows as \$i => \$row) {
            if ((string) (\$row['id'] ?? '') === \$id) {
                \$rows[\$i] = array_merge(\$row, \$item);
                \$replaced = true;
                break;
            }
        }
        if (!\$replaced) {
            \$rows[] = \$item;
        }
        ps_write(\$store, \$list, \$rows);
        ps_json(['ok' => true, 'list' => \$list, 'item' => \$item]);
        break;
    default:
        ps_json(['ok' => false, 'error' => 'unknown route'], 404);
}

PHP;
    }

    /**
     * @param list<string> $datasources
     */
    private function python(string $title, array $datasources): string
    {
        $dsJson = json_encode($datasources, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) ?: '[]';
        $safeTitle = addcslashes($title, '\\"');

        return <<<PY
#!/usr/bin/env python3
"""Generated by Power Sweeper export_web_ir (server_language=python).

Same JSON contract as api.php. Prefer PHP on hosts that already run it:

    python3 api.py
"""
from __future__ import annotations

import json
import re
import uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import parse_qs, urlparse

TITLE = "{$safeTitle}"
DATASOURCES = json.loads(r'''{$dsJson}''')
STORE = Path(__file__).resolve().parent / "data"
STORE.mkdir(parents=True, exist_ok=True)


def slug(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9._-]+", "_", name)


def read_list(name: str) -> list:
    path = STORE / f"{slug(name)}.json"
    if not path.is_file():
        return []
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError:
        return []
    return data if isinstance(data, list) else []


def write_list(name: str, rows: list) -> None:
    (STORE / f"{slug(name)}.json").write_text(
        json.dumps(rows, indent=2, ensure_ascii=False), encoding="utf-8"
    )


class Handler(BaseHTTPRequestHandler):
    def _send(self, payload: dict, code: int = 200) -> None:
        body = json.dumps(payload, ensure_ascii=False).encode("utf-8")
        self.send_response(code)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_OPTIONS(self) -> None:  # noqa: N802
        self.send_response(204)
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers", "Content-Type")
        self.end_headers()

    def do_GET(self) -> None:  # noqa: N802
        self._handle({})

    def do_POST(self) -> None:  # noqa: N802
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        try:
            body = json.loads(raw.decode("utf-8") or "{}")
        except json.JSONDecodeError:
            body = {}
        if not isinstance(body, dict):
            body = {}
        self._handle(body)

    def _handle(self, body: dict) -> None:
        qs = parse_qs(urlparse(self.path).query)
        route = (body.get("route") or (qs.get("route") or ["health"])[0] or "health")
        if route == "health":
            self._send({"ok": True, "app": TITLE, "language": "python", "datasources": DATASOURCES})
            return
        if route == "lists":
            self._send({"ok": True, "datasources": DATASOURCES})
            return
        if route == "items":
            name = str(body.get("list") or (qs.get("list") or [""])[0])
            if name not in DATASOURCES:
                self._send({"ok": False, "error": "unknown list"}, 404)
                return
            self._send({"ok": True, "list": name, "items": read_list(name)})
            return
        if route == "patch":
            name = str(body.get("list") or "")
            item = body.get("item") if isinstance(body.get("item"), dict) else {}
            if name not in DATASOURCES:
                self._send({"ok": False, "error": "unknown list"}, 404)
                return
            rows = read_list(name)
            ident = str(item.get("id") or item.get("ID") or uuid.uuid4())
            item["id"] = ident
            replaced = False
            for i, row in enumerate(rows):
                if str(row.get("id") or "") == ident:
                    rows[i] = {**row, **item}
                    replaced = True
                    break
            if not replaced:
                rows.append(item)
            write_list(name, rows)
            self._send({"ok": True, "list": name, "item": item})
            return
        self._send({"ok": False, "error": "unknown route"}, 404)

    def log_message(self, fmt: str, *args) -> None:
        return


if __name__ == "__main__":
    ThreadingHTTPServer(("127.0.0.1", 8787), Handler).serve_forever()

PY;
    }
}
